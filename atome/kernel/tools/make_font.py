#!/usr/bin/env python3
"""Makes font8x16.h: an 8x16 bitmap font for the Atome kernel's graphical screen (printable ASCII, 32..126),
by drawing DejaVu Sans Mono with Pillow and keeping the pixels that are dark enough.

    python3 atome/kernel/tools/make_font.py [--show]

DejaVu fonts: Copyright (c) 2003 Bitstream, Inc. (Bitstream Vera) and Tavmjong Bah (DejaVu changes, public domain).
Free to use, copy, modify and distribute; see https://dejavu-fonts.github.io/License.html.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
OUT = Path(__file__).resolve().parent.parent / "font8x16.h"


def glyph(ch: str, font) -> list[int]:
    img = Image.new("L", (16, 24), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    # the 8x16 cell: ascent of the font puts the baseline near row 13
    rows = []
    for y in range(16):
        bits = 0
        for x in range(8):
            if img.getpixel((x, y + 1)) > 110:
                bits |= 0x80 >> x
        rows.append(bits)
    return rows


def main() -> None:
    font = ImageFont.truetype(FONT, 13)
    glyphs = [glyph(chr(c), font) for c in range(32, 127)]
    if "--show" in sys.argv:
        for ch in "AaQg@{#%":
            for r in glyphs[ord(ch) - 32]:
                print("".join("#" if r & (0x80 >> x) else "." for x in range(8)))
            print()
    lines = ["// Generated by tools/make_font.py: 8x16 bitmap font, printable ASCII (32..126), one byte per row, top row first.",
             "// Drawn from DejaVu Sans Mono Bold (Bitstream Vera / DejaVu, free license: https://dejavu-fonts.github.io/License.html).",
             "static const unsigned char font8x16[95][16] = {"]
    for i, g in enumerate(glyphs):
        lines.append("    {" + ",".join(f"0x{b:02X}" for b in g) + "},  /* " + (chr(32 + i) if chr(32 + i) not in "\\/*" else "?") + " */")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


main()
